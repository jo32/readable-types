type Event = { kind: "cat"; meow: true } | { kind: "dog"; bark: true };

export type StringUnionCases = [
  Expect<Same<Trim<" \n hello\t\r ">, "hello">>,
  Expect<Same<Trim<string>, string>>,
  Expect<Same<Split<"a,b,c", ",">, ["a", "b", "c"]>>,
  Expect<Same<Split<"a,,", ",">, ["a", "", ""]>>,
  Expect<Same<Split<"", ",">, [""]>>,
  Expect<Same<Split<"", "">, []>>,
  Expect<Same<Split<"abc", "">, ["a", "b", "c"]>>,
  Expect<Same<Split<string, ",">, string[]>>,
  Expect<Same<Split<"abc", string>, string[]>>,
  Expect<Same<Join<readonly ["a", "b"], "/">, "a/b">>,
  Expect<Same<Join<["a"], "/">, "a">>,
  Expect<Same<Join<["a", "b"]>, "a,b">>,
  Expect<Same<Join<[], "/">, "">>,
  Expect<Same<Join<[string, "b"], "-">, `${string}-b`>>,
  Expect<Same<Join<string[], "/">, string>>,
  Expect<Same<Join<["a", ...string[]], "/">, string>>,
  // Join must reach the full 128-item budget without exceeding the recursion limit.
  Expect<Same<Split<Join<BuildTuple<128, "x">, ",">, ",">, BuildTuple<128, "x">>>,
  Expect<Same<Pipe<"  a,b,c  ", [TrimFn, SplitFn<",">, JoinFn<"/">]>, "a/b/c">>,
  Expect<Same<SelectMembers<"a" | "b", "b" | "c">, "b">>,
  Expect<Same<SelectMembers<Event, { kind: "dog" }>, { kind: "dog"; bark: true }>>,
  Expect<Same<Difference<"a" | "b", "b" | "c">, "a">>,
  Expect<Same<SymmetricDifference<"a" | "b", "b" | "c">, "a" | "c">>,
  Expect<Same<MapUnion<1 | 2, PromiseFn>, Promise<1> | Promise<2>>>,
  Expect<Same<MapUnion<never, PromiseFn>, never>>,
  Expect<Same<Pipe<1 | "a" | 2, [SelectMembersFn<number>, MapUnionFn<PromiseFn>]>, Promise<1> | Promise<2>>>,
  Expect<Same<Apply<ExcludeMembersFn<string>, 1 | "a">, 1>>,
  Expect<Same<UnionToIntersection<{ a: 1 } | { b: 2 }>, { a: 1 } & { b: 2 }>>,
  Expect<Same<UnionToIntersection<never>, never>>,
];
